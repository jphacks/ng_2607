"""Share character settings through Git as SQL.

Only the character content is exported: handle, public identity, profile, secrets, relationship
weights and automation settings. OAuth connections, browser sessions, relationships, game progress
and logs stay on each PC. Auto-reply and auto-post are always exported OFF so that two PCs never
run them for the same account; the importer keeps whatever is set locally.

Characters are matched by handle, so IDs may differ between PCs and re-importing never duplicates.
"""

from __future__ import annotations

import re

HEADER = """-- Re:Al Love Simulator: shared character settings
-- Generated by scripts/export_shared.py. Import with: .venv/bin/python scripts/import_shared.py
-- Contains no OAuth tokens, browser sessions, relationships or game progress.
-- Auto-reply / auto-post are not shared: the importer keeps each PC's own setting (OFF for new characters).
"""
CHARACTER_RE = re.compile(r"^-- character: (\S+)$", re.MULTILINE)
AUTOMATION_COLUMNS = ("post_prompt", "extra_persona", "schedule_base", "require_unlock", "unlock_score")


def literal(value):
    if value is None:
        return "NULL"
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def export_sql(db):
    """SQL that upserts every character with a handle, ordered by handle for stable diffs."""
    parts = [HEADER, "BEGIN;"]
    rows = db.execute("SELECT * FROM characters WHERE handle!='' ORDER BY lower(handle), id").fetchall()
    seen = set()
    for row in rows:
        handle = row["handle"]
        if handle.lower() in seen:
            continue  # Only the first character per handle is shared.
        seen.add(handle.lower())
        match = f"(SELECT id FROM characters WHERE lower(handle)=lower({literal(handle)}) ORDER BY id LIMIT 1)"
        values = {"name": row["name"], "profile": row["profile"], "at_did": row["at_did"],
                  "avatar_url": row["avatar_url"], "relationship_weights": row["relationship_weights"]}
        parts += [
            f"\n-- character: {handle}",
            f"INSERT INTO characters(name,profile,handle,at_did,avatar_url,relationship_weights,updated_at) "
            f"SELECT {literal(values['name'])},{literal(values['profile'])},{literal(handle)},{literal(values['at_did'])},"
            f"{literal(values['avatar_url'])},{literal(values['relationship_weights'])},strftime('%s','now') "
            f"WHERE NOT EXISTS (SELECT 1 FROM characters WHERE lower(handle)=lower({literal(handle)}));",
            # A different account behind the handle invalidates the local OAuth connection.
            f"UPDATE characters SET oauth_did=CASE WHEN at_did={literal(values['at_did'])} THEN oauth_did ELSE '' END,"
            f"oauth_owner=CASE WHEN at_did={literal(values['at_did'])} THEN oauth_owner ELSE '' END,"
            + ",".join(f"{column}={literal(value)}" for column, value in values.items())
            + f",updated_at=strftime('%s','now') WHERE id={match};",
            f"DELETE FROM character_secrets WHERE character_id={match};",
        ]
        for secret in db.execute("SELECT level,title,content FROM character_secrets WHERE character_id=? ORDER BY level", (row["id"],)):
            parts.append(f"INSERT INTO character_secrets(character_id,level,title,content) "
                         f"VALUES({match},{secret['level']},{literal(secret['title'])},{literal(secret['content'])});")
        automation = db.execute("SELECT * FROM character_automation WHERE character_id=?", (row["id"],)).fetchone()
        if automation is not None:
            columns = ",".join(AUTOMATION_COLUMNS)
            values_sql = ",".join(literal(automation[column]) for column in AUTOMATION_COLUMNS)
            updates = ",".join(f"{column}=excluded.{column}" for column in AUTOMATION_COLUMNS)
            parts.append(f"INSERT INTO character_automation(character_id,auto_reply,auto_post,{columns},updated_at) "
                         f"SELECT {match},0,0,{values_sql},strftime('%s','now') WHERE {match} IS NOT NULL "
                         f"ON CONFLICT(character_id) DO UPDATE SET {updates},updated_at=excluded.updated_at;")
    parts.append("\nCOMMIT;\n")
    return "\n".join(parts)


def shared_handles(sql):
    return CHARACTER_RE.findall(sql)


def import_sql(db, sql):
    """Run an exported file. Returns (added, updated) handles."""
    if not sql.startswith(HEADER.splitlines()[0]):
        raise ValueError("scripts/export_shared.py で書き出したファイルではありません")
    handles = shared_handles(sql)
    existing = {row["handle"].lower() for row in db.execute("SELECT handle FROM characters WHERE handle!=''")}
    db.executescript(sql)
    return [h for h in handles if h.lower() not in existing], [h for h in handles if h.lower() in existing]
